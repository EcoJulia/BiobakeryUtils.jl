function _gf_parse(gf)
    if contains(gf, '|') # indicates a taxon-stratified entry
        (gf, tax) = split(gf, '|')
        if tax == "unclassified"
            tax = Taxon("unclassified")
        else
            tax = String(tax)
            tm = contains(tax, "s__") ? match(r"(s__)(\w+)", tax) :
                contains(tax, "g__") ? match(r"(g__)(\w+)", tax) :
                match(r"^(\W*)(\w+)$", tax)
            isnothing(tm) && error("Incorrectly formatted taxon stratification: $tax")
            cld = isnothing(tm.captures[1]) || tm.captures[1] == "s__" ? :species : :genus
            tax = Taxon(string(tm.captures[2]), cld)
        end
        return GeneFunction(gf, tax)
    else
        return GeneFunction(gf)
    end
end

"""
    humann_profile(path::AbstractString; sample, stratified=false)

Load a single functional profile generated by `HUMAnN`.
By default, skips rows that have species-stratified content,
use `stratified=true` to keep them.
Plain, gzip, and XZ paths are supported. `sample` may be a name or a sample object;
the default name is the filename without table/compression suffixes.
"""
function humann_profile(path::AbstractString; sample = _source_name(path), stratified = false)
    table = read_humann(path)
    kept = findall(key -> stratified || !occursin('|', key), table.feature)
    gfs = GeneFunction[_gf_parse(key) for key in table.feature[kept]]
    values = table.abundance[kept]
    return CommunityProfile(sparse(reshape(values, length(values), 1)), gfs, [_profile_sample(sample)])
end

"""
    humann_profiles(path::AbstractString; samples=nothing, stratified=false)

Load a joined HUMAnN table (multiple samples) into a `CommunityProfile`.
Plain, gzip, and XZ paths are supported. Missing values become zero. `samples`
overrides column names and may contain sample objects with metadata. The sparse
matrix is assembled in bulk, retaining zero-only features.
"""
function humann_profiles(path::AbstractString; samples = nothing, stratified = false, skipto = 2)
    tbl = _csv_profile(path) do source
        CSV.File(source; skipto)
    end
    columns = collect(Tables.columnnames(tbl))
    length(columns) >= 2 || throw(ArgumentError("HUMAnN table requires at least one sample column."))
    if !isnothing(samples)
        length(samples) == length(columns) - 1 || throw(ArgumentError("Passed $(length(samples)) samples, but table has $(length(columns) - 1)"))
    else
        samples = columns[2:end]
    end

    feature_column = Tables.getcolumn(tbl, 1)
    kept = findall(key -> stratified || !occursin('|', key), feature_column)
    gfs = GeneFunction[_gf_parse(key) for key in feature_column[kept]]
    mat = _table_abundances(tbl, kept, 2:length(columns))
    return CommunityProfile(mat, gfs, _table_sample.(samples))
end

"""
    humann_profiles(paths::AbstractVector{<:AbstractString}; samples=nothing, stratified=false)

Read multiple single-sample HUMAnN tables into one profile. Features are aligned in
first-occurrence order, and samples follow path order. Plain, gzip, and XZ files
may be mixed. No intermediate CommunityProfiles or persistent indexes are built.
"""
function humann_profiles(paths::AbstractVector{<:AbstractString}; samples = nothing, stratified = false)
    return _load_profiles(paths, HUMAnNFormat(stratified); samples)
end

"""
    read_pcl(infile; last_metadata=2)

Reads a [PCL file](https://software.broadinstitute.org/cancer/software/gsea/wiki/index.php/Data_formats#PCL:_Stanford_cDNA_file_format_.28.2A.pcl.29)
and generates a `CommunityProfile` with metadata attached to the samples.

`last_metadata` may be a row number or a string representing the final metadatum.
"""
function read_pcl(infile; last_metadata = 2)
    if last_metadata isa Int
        lr = last_metadata
    else
        lr = 1
        for line in eachline(infile)
            startswith(line, last_metadata) && break
            lr += 1
        end
    end

    md_rows = CSV.File(infile, limit = lr - 1, threaded = false)
    cols = keys(first(md_rows))[2:end]
    gfs = humann_profiles(infile; stratified = true, skipto = lr + 1)
    for row in md_rows
        md = Symbol(row[1])
        for col in cols
            set!(gfs, string(col), md, row[col])
        end
    end
    return gfs
end

"""
    write_pcl(path, comm::CommunityProfile; usemetadata=:all)

Writes a [PCL file](https://software.broadinstitute.org/cancer/software/gsea/wiki/index.php/Data_formats#PCL:_Stanford_cDNA_file_format_.28.2A.pcl.29)
from a `CommunityProfile` with metadata attached to the samples.

`usemetadata` may be `:all` or a vector of symbols.
"""
function write_pcl(path, comm::CommunityProfile; usemetadata = :all)
    coltab = Tables.columntable(get(comm))
    if usemetadata == :all
        usemetadata = collect(keys(coltab))
        popfirst!(usemetadata)
    end
    cols = Symbol.(coltab.sample)
    pushfirst!(cols, :thing)
    tbl = (; zip(cols, [[usemetadata]..., [[coltab[md][i] for md in usemetadata] for i in 1:(length(cols) - 1)]...])...)
    CSV.write(path, tbl; delim = '\t')

    return CSV.write(path, comm; append = true, delim = '\t')
end
